            <h3><i class="fas fa-tools"></i> Features</h3>
            <ul class="feature-list">
                <li><i class="fas fa-magic"></i> <strong>Scrape Info</strong> — Paste an auksjonen.no link and auto-fetch the title and production year.</li>
                <li><i class="fas fa-edit"></i> <strong>Edit Live Sales</strong> — Edit all fields of an active sale at any time via an inline modal.</li>
                <li><i class="fas fa-check"></i> <strong>Mark as Sold</strong> — Move a sale to Finished directly from the Live Sales edit modal or with the green checkmark button, or when adding a new sale.</li>
                <li><i class="fas fa-trash"></i> <strong>Delete Sales</strong> — Remove any sale permanently from both Live and Finished Sales.</li>
                <li><i class="fas fa-tag"></i> <strong>Final Price Tracking</strong> — Add or update the final sale price on finished items to calculate ROI.</li>
                <li><i class="fas fa-sync-alt"></i> <strong>Auto Status Update</strong> — Sales whose finish date has passed are automatically moved to Finished Sales on every page load.</li>
                <li><i class="fas fa-external-link-alt"></i> <strong>Direct Auction Links</strong> — One-click icon to open the original auction listing in a new tab.</li>
            </ul>
